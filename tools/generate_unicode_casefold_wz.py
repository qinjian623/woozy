#!/usr/bin/env python3
"""Generate full default case folding from the pinned Unicode 18.0.0 data."""

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tests/native/unicode/data/CaseFolding.txt"
OUTPUT = ROOT / "stdlib/unicode/unicode_casefold_table.wz"
SOURCE_SHA256 = "a004797658a457bec4dc11683e39f69249ea3b595b752dbea6721c4c9f587b0d"


def load_mappings(path):
    source = path.read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise SystemExit(f"{path}: SHA-256 does not match pinned Unicode 18.0.0")
    mappings = {}
    for line in source.decode("utf-8").splitlines():
        fields = line.partition("#")[0].split(";")
        if len(fields) > 2 and fields[1].strip() in ("C", "F"):
            rune = int(fields[0], 16)
            mappings[rune] = tuple(int(value, 16) for value in fields[2].split())
    return mappings


def group_mappings(mappings):
    groups = []
    for rune, result in sorted(mappings.items()):
        if rune < 128:
            continue  # The library handles ASCII directly.
        delta = result[0] - rune if len(result) == 1 else None
        if groups and delta is not None:
            start, end, stride, previous_delta, _ = groups[-1]
            distance = rune - end
            if delta == previous_delta and distance in (1, 2) and stride in (0, distance):
                groups[-1] = start, rune, distance, delta, None
                continue
        groups.append((rune, rune, 0, delta, result))
    return groups


def mapped_expression(delta, result):
    if delta is None:
        return str(sum(rune << (21 * index) for index, rune in enumerate(result)))
    if delta > 0:
        return f"u64(rune + {delta})"
    return f"u64(rune - {-delta})"


def emit_groups(groups, indent):
    if len(groups) <= 4:
        for start, end, stride, delta, result in groups:
            condition = f"rune == {start}"
            if start != end:
                condition = f"rune >= {start} && rune <= {end}"
                if stride == 2:
                    condition += f" && (rune & 1) == {start & 1}"
            expression = mapped_expression(delta, result)
            yield f"{indent}if {condition} {{ return {expression}; }}"
        yield f"{indent}return 0;"
        return

    middle = len(groups) // 2
    yield f"{indent}if rune < {groups[middle][0]} {{"
    yield from emit_groups(groups[:middle], indent + "    ")
    yield f"{indent}}}"
    yield from emit_groups(groups[middle:], indent)


def generate(mappings):
    lines = [
        "// Generated by tools/generate_unicode_casefold_wz.py from Unicode 18.0.0 CaseFolding.txt C/F entries.",
        "package unicode;",
        "",
        "// Each 21-bit field contains one output scalar, least significant first.",
        "// Zero denotes identity. No CaseFolding.txt entry contains U+0000.",
        "func casefold_mapping(rune u32) u64 {",
        *emit_groups(group_mappings(mappings), "    "),
        "}",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(load_mappings(args.source)).encode("utf-8")
    if args.check:
        if args.output.read_bytes() != generated:
            raise SystemExit(f"{args.output}: regenerate with {Path(__file__).name}")
        return
    args.output.write_bytes(generated)


if __name__ == "__main__":
    main()
