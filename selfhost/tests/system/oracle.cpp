// Test-only oracle and deterministic generator for the frozen system-operation
// metadata. It includes the compiler header directly; it does not link against
// the old frontend or any compiler library.
//
//   oracle --emit-wz > selfhost/src/wzcc/system/system.wz
//   oracle --dump    # canonical dump used by run.sh
//
// The generated Woozy file is checked in; woozyc never reads this header.
#include <cstdio>
#include <cstdlib>
#include <map>
#include <set>
#include <string>
#include <string_view>
#include <vector>

#include "lang/hir/system_operation.hpp"

namespace {

using lang::hir::SystemOperationSpec;

[[noreturn]] void die(const std::string &message) {
  std::fprintf(stderr, "oracle: %s\n", message.c_str());
  std::exit(1);
}

std::string quoted(std::string_view text) {
  std::string out = "\"";
  for (char c : text) {
    if (c == '"' || c == '\\') {
      out += '\\';
      out += c;
    } else if (static_cast<unsigned char>(c) < 0x20 && c != '\t') {
      die("unexpected control byte in metadata");
    } else {
      out += c;
    }
  }
  out += '"';
  return out;
}

// The resolver prelude order in src/modules/resolve.cpp. run.sh separately
// extracts that list from the resolver source and compares it with the
// builtin_types() dump, so this literal is only a generator convenience.
constexpr const char *builtin_types[] = {
    "Unit",      "bool",      "i8",         "i16",        "i32",
    "i64",       "u8",        "u16",        "u32",        "u64",
    "isize",     "usize",     "f32",        "f64",        "string",
    "Vec",       "Slice",     "Weak",       "Task",       "Result",
    "Ptr",       "PtrMut",    "Buffer",     "BufferMut",  "__woozy_Thread",
    "__woozy_Mutex", "__woozy_Condvar", "__woozy_AtomicI64", "__woozy_IpcHandle",
};

std::string_view parameter(const SystemOperationSpec &spec, std::size_t i) {
  if (i >= spec.parameters.size())
    die("parameter index outside frozen array");
  return spec.parameters[i];
}

void validate(const std::vector<const SystemOperationSpec *> &specs) {
  std::set<unsigned> operations;
  std::set<std::string_view> names;
  for (const auto *spec : specs) {
    unsigned number = static_cast<unsigned>(spec->operation);
    if (!operations.insert(number).second)
      die("duplicate operation number " + std::to_string(number));
    if (!names.insert(spec->name).second)
      die("duplicate operation name " + std::string(spec->name));
    if (spec->name.empty() || spec->result.empty() || spec->owner.empty())
      die("empty name, result, or owner");
    if (spec->count > spec->parameters.size())
      die("parameter count exceeds frozen storage");
    for (std::size_t i = spec->count; i < spec->parameters.size(); ++i)
      if (!spec->parameters[i].empty())
        die("non-empty parameter beyond declared count for " +
            std::string(spec->name));
    for (std::size_t i = 0; i < spec->count; ++i)
      if (parameter(*spec, i).empty())
        die("empty parameter inside declared count for " +
            std::string(spec->name));
  }
}

std::vector<const SystemOperationSpec *> ordered() {
  std::vector<const SystemOperationSpec *> specs;
  specs.reserve(lang::hir::all_system_operations.size());
  for (const auto &spec : lang::hir::all_system_operations) specs.push_back(&spec);
  validate(specs);
  return specs;
}

void emit_wz(const std::vector<const SystemOperationSpec *> &specs) {
  std::printf(
      "// Generated by selfhost/tests/system/oracle.cpp --emit-wz from\n"
      "// include/lang/hir/system_operation.hpp. Do not edit by hand.\n"
      "package system;\n"
      "\n"
      "pub struct OperationSpec {\n"
      "    pub operation u32;\n"
      "    pub name string;\n"
      "    pub result string;\n"
      "    pub parameters Vec[string];\n"
      "    pub owner string;\n"
      "    pub type_arity u32;\n"
      "}\n"
      "\n"
      "pub func operations() Vec[OperationSpec] {\n"
      "    return [\n");
  for (const auto *spec : specs) {
    std::string line = "        OperationSpec(operation: ";
    line += std::to_string(static_cast<unsigned>(spec->operation));
    line += ", name: ";
    line += quoted(spec->name);
    line += ", result: ";
    line += quoted(spec->result);
    line += ", parameters: [";
    for (std::size_t i = 0; i < spec->count; ++i) {
      if (i != 0) line += ", ";
      line += quoted(parameter(*spec, i));
    }
    line += "], owner: ";
    line += quoted(spec->owner);
    line += ", type_arity: ";
    line += std::to_string(spec->type_arity);
    line += "),\n";
    std::fputs(line.c_str(), stdout);
  }
  std::printf(
      "    ];\n"
      "}\n"
      "\n"
      "pub func builtin_types() Vec[string] {\n"
      "    return [\n");
  for (const char *type : builtin_types)
    std::printf("        %s,\n", quoted(type).c_str());
  std::printf("    ];\n}\n");
}

void emit_dump(const std::vector<const SystemOperationSpec *> &specs) {
  std::printf("operations %zu\n", specs.size());
  for (const auto *spec : specs) {
    std::printf("op %u\n", static_cast<unsigned>(spec->operation));
    std::printf("name %s\n", std::string(spec->name).c_str());
    std::printf("result %s\n", std::string(spec->result).c_str());
    std::printf("owner %s\n", std::string(spec->owner).c_str());
    std::printf("arity %u\n", spec->type_arity);
    std::printf("params %zu\n", static_cast<std::size_t>(spec->count));
    for (std::size_t i = 0; i < spec->count; ++i)
      std::printf("param %s\n", std::string(parameter(*spec, i)).c_str());
    std::printf("end\n");
  }
}

} // namespace

int main(int argc, char **argv) {
  auto specs = ordered();
  if (argc != 2) die("usage: oracle --emit-wz|--dump");
  std::string_view mode = argv[1];
  if (mode == "--emit-wz")
    emit_wz(specs);
  else if (mode == "--dump")
    emit_dump(specs);
  else
    die("usage: oracle --emit-wz|--dump");
  return 0;
}
