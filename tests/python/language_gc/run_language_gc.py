#!/usr/bin/env python3
"""Build and observe the eight real Wz language-GC programs.

Two modes are supported.

Legacy default
    ``--helper`` only, exactly like the original CMake invocation.  Each case
    is emitted by the C++ ``lang_python_emit`` helper and then observed by the
    unchanged ``observe_language_gc.py``.  The same ``--out`` may be reused;
    every invocation gets its own ``runs/<id>`` evidence directory so old
    records are never overwritten.

Paired public-API mode
    ``--cli``/``--helper`` for the reference group and
    ``--candidate-cli``/``--api-driver`` for the candidate group.  Every case
    performs a real CLI build, one real API/helper emit, and one unchanged
    observer run (8 x 3 x 2 = 48 main commands).  The API emit is accepted for
    metadata only after the CLI and API ``program.py``/``langrt.py`` bytes are
    identical.  The observer always imports the CLI-generated bytes.

The candidate API driver is the prebuilt Wz ``pythonobs`` from the historical
SH14 evidence.  It is used only as a separately labelled symbols aid: its old
Source identity and build record are checked against ``driver-inputs.json``.
It is not a claim that the current Source's PythonEmitter API was rebuilt.

Every real process uses ``selfhost/corpus.py::_run_process_impl``; every
command records native exit type, strict timeout/cleanup/pipe booleans, raw
stdout/stderr, SHAs and (when strace is supplied) an exec trace immediately.
No ``_f``/``_s`` name is guessed or parsed from generated Python.
"""
