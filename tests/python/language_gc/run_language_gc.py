def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def digest(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def digest_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True,
                               ensure_ascii=False) + '\n', encoding='utf-8')


def decode_bytes(data: bytes) -> str:
    return data.decode('utf-8', errors='replace')


def canonical_sha(value) -> str:
    return hashlib.sha256(
        json.dumps(value, ensure_ascii=False, sort_keys=True,
                   separators=(',', ':')).encode('utf-8')).hexdigest()


def label_name(text: str) -> str:
    return ''.join(character if character.isalnum() or character in '-_.'
                   else '_' for character in text)


def finite_timeout(text: str) -> float:
    try:
        value = float(text)
    except ValueError as error:
        raise argparse.ArgumentTypeError(
            '--timeout must be finite and positive') from error
    if not math.isfinite(value) or value <= 0:
        raise argparse.ArgumentTypeError('--timeout must be finite and positive')
    return value


def prepare_output(out: Path, strict: bool) -> None:
    if out.exists():
        if not out.is_dir():
            raise RuntimeError(f'--out is not a directory: {out}')
        if strict and any(out.iterdir()):
            raise RuntimeError(
                f'refusing to overwrite existing evidence in --out: {out}')
    out.mkdir(parents=True, exist_ok=True)


def unique_run_dir(out: Path, prefix: str) -> Path:
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    base = out / 'runs' / f'{prefix}-{stamp}-{os.getpid()}'
    candidate = base
    index = 1
    while candidate.exists():
        candidate = Path(str(base) + f'-{index}')
        index += 1
    candidate.mkdir(parents=True, exist_ok=False)
    return candidate


def environment(toolchain_root: Path | None, work: Path) -> dict[str, str]:
    env = dict(os.environ)
    env['PYTHONDONTWRITEBYTECODE'] = '1'
    env['PYTHONNOUSERSITE'] = '1'
    env.pop('PYTHONPATH', None)
    if toolchain_root is not None and toolchain_root.is_dir():
        paths = []
        llvm = toolchain_root / 'llvm-22.1.8' / 'lib'
        libxml = toolchain_root / 'libxml2-legacy-2.13.9' / 'usr' / 'lib'
        if llvm.is_dir():
            paths.append(str(llvm))
        if libxml.is_dir():
            paths.append(str(libxml))
        if env.get('LD_LIBRARY_PATH'):
            paths.append(env['LD_LIBRARY_PATH'])
        env['LD_LIBRARY_PATH'] = ':'.join(paths)
    tmp = work / 'tmp'
    tmp.mkdir(parents=True, exist_ok=True)
    env['TMPDIR'] = str(tmp)
    return env


def run_command(argv, cwd: Path, timeout: float, out: Path,
                log: list[dict], label: str, env: dict[str, str],
                strace: Path | None = None, *,
                audit_allowed: set[str] | None = None,
                trace_scope: str = COMPILER_TRACE_SCOPE,
                meta: dict | None = None) -> dict:
    """Run one real command through the shared bounded process helper."""
    if not math.isfinite(timeout) or timeout <= 0:
        raise RuntimeError(f'{label}: timeout must be finite and positive')
    logs = out / 'logs'
    logs.mkdir(parents=True, exist_ok=True)
    sequence = len(log)
    stem = f'{sequence:03d}-{label_name(label)}'
    stdout_path = logs / f'{stem}.stdout'
    stderr_path = logs / f'{stem}.stderr'
    tool_argv = [str(part) for part in argv]
    real_argv = list(tool_argv)
    trace_path = None
    if strace is not None:
        traces = out / 'traces'
        traces.mkdir(parents=True, exist_ok=True)
        trace_path = traces / f'{stem}.trace'
        real_argv = [str(strace), '--seccomp-bpf', '-f', '-qq', '-s',
                     '16384', '-e', 'trace=execve,execveat', '-o',
                     str(trace_path), *real_argv]
    started = time.monotonic()
    process = _run_process_impl(real_argv, cwd, env, timeout)
    elapsed = time.monotonic() - started
    stdout_path.write_bytes(process['stdout'])
    stderr_path.write_bytes(process['stderr'])
    record = dict(meta or {})
    record.update({
        'label': label,
        'argv': real_argv,
        'tool_argv': tool_argv,
        'cwd': str(cwd),
        'timeout_seconds': timeout,
        'elapsed_seconds': elapsed,
        'exit': process['exit'],
        'timed_out': process['timed_out'],
        'cleanup_complete': process['cleanup_complete'],
        'abandoned_pipes': process['abandoned_pipes'],
        'stdout_path': str(stdout_path),
        'stderr_path': str(stderr_path),
        'stdout_sha256': digest_bytes(process['stdout']),
        'stderr_sha256': digest_bytes(process['stderr']),
        'stdout': decode_bytes(process['stdout']),
        'stderr': decode_bytes(process['stderr']),
    })
    if trace_path is not None:
        record['trace_path'] = str(trace_path)
        record['trace_sha256'] = digest(trace_path) if trace_path.is_file() else ''
        record['trace_scope'] = trace_scope
    else:
        record['trace_path'] = None
        record['trace_sha256'] = None
        record['trace_scope'] = None

    def persist() -> None:
        """Save the actual command before audit/validation can fail."""
        if not log or log[-1] is not record:
            log.append(record)
        destination = out / 'commands.jsonl'
        pending = destination.with_name(destination.name + '.pending')
        with pending.open('w', encoding='utf-8') as stream:
            for item in log:
                stream.write(json.dumps(item, ensure_ascii=False,
                                        sort_keys=True) + '\n')
        pending.replace(destination)

    persist()
    if audit_allowed is not None:
        if trace_path is None:
            record['trace_audit_error'] = f'{label}: command was not traced'
            persist()
            raise RuntimeError(record['trace_audit_error'])
        try:
            audit = audit_trace(trace_path, audit_allowed)
        except TraceError as error:
            record['trace_audit_error'] = f'{type(error).__name__}: {error}'
            persist()
            raise RuntimeError(
                f'{label}: exact exec whitelist rejected trace: {error}') from error
        except Exception as error:
            record['trace_audit_error'] = f'{type(error).__name__}: {error}'
            persist()
            raise
        if set(audit['observed']) != set(audit_allowed):
            message = (f'{label}: expected exactly {sorted(audit_allowed)}, '
                       f'observed {audit["observed"]}')
            record['trace_audit_error'] = f'TraceSetError: {message}'
            persist()
            raise RuntimeError(message)
        record['trace_audit'] = audit
        persist()
        write_json(Path(str(trace_path) + '.audit.json'), {
            'label': label,
            'trace_scope': trace_scope,
            **audit,
        })
    return record


def require_ok(record: dict, expected_exit: int = 0) -> None:
    if (type(record.get('exit')) is not int
            or record['exit'] != expected_exit
            or record.get('timed_out') is not False
            or record.get('cleanup_complete') is not True
            or record.get('abandoned_pipes') is not False):
        raise RuntimeError(
            f"{record.get('label')}: exit {record.get('exit')!r} "
            f"timed_out={record.get('timed_out')!r} "
            f"cleanup_complete={record.get('cleanup_complete')!r} "
            f"abandoned_pipes={record.get('abandoned_pipes')!r}\n"
            f"stdout:\n{record.get('stdout')}\nstderr:\n{record.get('stderr')}")


def parse_json_record(record: dict) -> dict:
    try:
        document = json.loads(record['stdout'],
                              parse_constant=_reject_json_constant)
    except (json.JSONDecodeError, CorpusError) as error:
        raise RuntimeError(
            f"{record.get('label')}: expected strict JSON, got "
            f"{record.get('stdout')!r}: {error}") from error
    if not isinstance(document, dict):
        raise RuntimeError(f"{record.get('label')}: JSON is not an object")
    return document


def load_strict_json(path: Path, label: str) -> dict:
    try:
        document = json.loads(path.read_text(encoding='utf-8'),
                              parse_constant=_reject_json_constant)
    except (OSError, UnicodeDecodeError, json.JSONDecodeError, CorpusError) as error:
        raise RuntimeError(f'{label}: cannot read strict JSON {path}: {error}') from error
    if not isinstance(document, dict):
        raise RuntimeError(f'{label}: JSON is not an object: {path}')
    return document


def check_original_inputs(*, frozen_cmake: bool = True) -> dict:
    source = HERE / 'source.wz'
    observer = HERE / 'observe_language_gc.py'
    cmake = COMPILER_ROOT / 'tests/python/CMakeLists.txt'
    for path in (source, observer, cmake):
        if not path.is_file():
            raise RuntimeError(f'missing original input: {path}')
    source_sha = digest(source)
    observer_sha = digest(observer)
    cmake_bytes = cmake.read_bytes()
    cmake_sha = digest_bytes(cmake_bytes)
    if source_sha != SOURCE_SHA256 or source.stat().st_size != SOURCE_BYTES:
        raise RuntimeError(
            f'original source.wz changed: {source_sha} / {source.stat().st_size}')
    if observer_sha != OBSERVER_SHA256:
        raise RuntimeError(f'original observer changed: {observer_sha}')
    if frozen_cmake:
        if cmake_sha != CMAKE_SHA256:
            raise RuntimeError(f'tests/python/CMakeLists.txt changed: {cmake_sha}')
    elif cmake_bytes.count(LEGACY_CMAKE_REGISTRATION) != 1:
        raise RuntimeError('python.language_gc_source CMake registration changed')
    observer_text = observer.read_text(encoding='utf-8')
    disable = observer_text.find('gc.disable()')
    forbid = observer_text.find('gc.collect = forbid_host_collection')
    import_rt = observer_text.find('import langrt as rt')
    import_program = observer_text.find('import program')
    if not (0 <= disable < import_rt and 0 <= forbid < import_rt
            and 0 <= import_rt < import_program):
        raise RuntimeError(
            'observer no longer disables CPython GC/forbids gc.collect '
            'before importing langrt/program')
    return {
        'source.wz': source_sha,
        'observe_language_gc.py': observer_sha,
        'tests/python/CMakeLists.txt': cmake_sha,
        'source_bytes': source.stat().st_size,
    }


def check_runtime(directory: Path, label: str) -> None:
    runtime = directory / 'langrt.py'
    if not runtime.is_file():
        raise RuntimeError(f'{label}: no generated langrt.py')
    if RUNTIME_VERSION_LINE not in runtime.read_text(encoding='utf-8'):
        raise RuntimeError(f'{label}: generated runtime is not {RUNTIME_VERSION}')


def entry_hashes(directory: Path, label: str) -> dict:
    program = directory / 'program.py'
    runtime = directory / 'langrt.py'
    if not program.is_file() or not runtime.is_file():
        raise RuntimeError(f'{label}: did not publish program.py and langrt.py')
    check_runtime(directory, label)
    return {
        'program.py': digest(program),
        'langrt.py': digest(runtime),
    }


def compare_generated_files(first: Path, second: Path, label: str) -> dict:
    hashes = {}
    for name in ('program.py', 'langrt.py'):
        left = first / name
        right = second / name
        if not left.is_file() or not right.is_file():
            raise RuntimeError(f'{label}: missing generated {name}')
        left_sha = digest(left)
        right_sha = digest(right)
        if left_sha != right_sha:
            raise RuntimeError(
                f'{label}: CLI/API disagree on generated {name} '
                f'({left_sha} != {right_sha})')
        hashes[name] = left_sha
    return hashes


def source_metadata(api_kind: str, compared: dict) -> dict:
    """Describe metadata provenance without claiming a current API rebuild."""
    if api_kind == 'helper':
        origin = 'reference C++ helper metadata.json'
        history = 'unknown'
        proof_status = 'unknown'
    else:
        origin = 'historical Wz pythonobs 55d5... from old Source 727b'
        history = ('old Source tree 727b; current Source da69 PythonEmitter '
                   'API was not rebuilt')
        proof_status = 'false'
    return {
        'origin': origin,
        'compiled_source_history': history,
        'current_source_same_api_proof': False,
        'current_source_same_api_proof_status': proof_status,
        'same_generated_bytes_sha256': dict(compared),
        'byte_equality_scope': (
            'CLI and API/helper emitted identical program.py and langrt.py; '
            'this proves the actual alias selection and bytes for this run, '
            'not the compiler Source or PythonEmitter API identity.'),
    }


def select_required_symbols(rows, label: str) -> list[dict]:
    """Select the eight real function rows; never invent or regex a name."""
    if not isinstance(rows, list):
        raise RuntimeError(f'{label}: symbols/functions is not a list')
    found: dict[str, str] = {}
    for item in rows:
        if not isinstance(item, dict):
            raise RuntimeError(f'{label}: symbol row is not an object: {item!r}')
        source_name = item.get('source_name')
        generated = item.get('generated')
        if not isinstance(source_name, str) or not source_name:
            raise RuntimeError(f'{label}: invalid source_name: {item!r}')
        if not isinstance(generated, str) or not generated:
            raise RuntimeError(f'{label}: invalid generated name: {item!r}')
        if source_name not in REQUIRED_FUNCTIONS:
            continue
        if source_name in found:
            raise RuntimeError(
                f'{label}: duplicate required source_name {source_name!r}')
        found[source_name] = generated
    missing = [name for name in REQUIRED_FUNCTIONS if name not in found]
    if missing:
        raise RuntimeError(
            f'{label}: missing required source_name(s): {missing}; '
            f'published rows: {sorted(found)}')
    if len(set(found.values())) != len(found):
        raise RuntimeError(f'{label}: duplicate generated names: {found}')
    return [{'source_name': name, 'generated': found[name]}
            for name in REQUIRED_FUNCTIONS]


def read_reference_metadata(directory: Path, label: str) -> tuple[list[dict], dict, Path]:
    path = directory / 'metadata.json'
    if not path.is_file():
        raise RuntimeError(f'{label}: helper wrote no metadata.json')
    document = load_strict_json(path, label)
    selected = None
    for key in ('functions', 'symbols'):
        rows = document.get(key)
        if isinstance(rows, list):
            current = select_required_symbols(rows, f'{label}.{key}')
            if selected is None:
                selected = current
            elif current != selected:
                raise RuntimeError(
                    f'{label}: metadata functions/symbols disagree for the '
                    f'required names')
    if selected is None:
        raise RuntimeError(
            f'{label}: metadata.json has neither functions nor symbols')
    return selected, document, path


def read_candidate_metadata(record: dict, label: str) -> tuple[list[dict], dict]:
    document = parse_json_record(record)
    if document.get('status') != 'ok':
        raise RuntimeError(f'{label}: API status is not ok: {document}')
    rows = document.get('symbols')
    if not isinstance(rows, list):
        raise RuntimeError(f'{label}: API stdout has no symbols array')
    return select_required_symbols(rows, label), document


def cli_metadata_crosscheck(directory: Path, api_rows: list[dict],
                            label: str) -> dict:
    path = directory / 'metadata.json'
    if not path.is_file():
        return {'status': 'absent', 'path': None, 'sha256': None}
    document = load_strict_json(path, label)
    recognized = False
    for key in ('functions', 'symbols'):
        rows = document.get(key)
        if isinstance(rows, list):
            recognized = True
            current = select_required_symbols(rows, f'{label}.{key}')
            if current != api_rows:
                raise RuntimeError(
                    f'{label}: CLI metadata {key} disagree with API symbols')
    if not recognized:
        return {'status': 'unrecognized', 'path': str(path),
                'sha256': digest(path)}
    return {'status': 'matched', 'path': str(path), 'sha256': digest(path)}


def project_metadata(cli_dir: Path, case_dir: Path, rows: list[dict],
                     source: str) -> dict:
    original = cli_dir / 'metadata.json'
    original_sha = None
    if original.is_file():
        original_sha = digest(original)
        shutil.copyfile(original, cli_dir / 'metadata.cli-original.json')
    projected = {'schema_version': 1, 'functions': rows}
    write_json(original, projected)
    projected_sha = digest(original)
    details = {
        'source': source,
        'functions': rows,
        'cli_original_sha256': original_sha,
        'projected_sha256': projected_sha,
        'projected_path': str(original),
    }
    write_json(case_dir / 'metadata-projection.json', details)
    return details


def check_observation(case: str, document: dict) -> dict:
    if not isinstance(document, dict):
        raise RuntimeError(f'{case}: observer output is not an object')
    if set(document) != OBSERVATION_KEYS:
        raise RuntimeError(
            f'{case}: observer keys {sorted(document)} != '
            f'{sorted(OBSERVATION_KEYS)}')
    if document.get('case') != case:
        raise RuntimeError(
            f'{case}: observer reported case {document.get("case")!r}')
    if type(document.get('live')) is not int or document['live'] != 0:
        raise RuntimeError(f'{case}: observer live is not 0: {document!r}')
    stats = document.get('stats')
    if not isinstance(stats, dict):
        raise RuntimeError(f'{case}: observer stats is not an object')
    missing = STATS_KEYS - set(stats)
    if missing:
        raise RuntimeError(f'{case}: observer stats missing {sorted(missing)}')
    if stats.get('runtime_version') != RUNTIME_VERSION:
        raise RuntimeError(f'{case}: wrong runtime version {stats!r}')
    if stats.get('active') is not False:
        raise RuntimeError(f'{case}: collector still active: {stats!r}')
    for key in ('live', 'busy', 'last_collected', 'collections', 'polls',
                'total_collected', 'weak_dead'):
        if type(stats.get(key)) is not int:
            raise RuntimeError(f'{case}: stats.{key} is not an int: {stats!r}')
        if stats[key] < 0:
            raise RuntimeError(f'{case}: stats.{key} is negative: {stats!r}')
    if stats['live'] != 0 or stats['busy'] != 0:
        raise RuntimeError(f'{case}: non-zero live/busy stats: {stats!r}')
    minimum = {
        'self-cycle': 1,
        'two-cycles': 2,
        'duplicate-edges': 2,
        'dead-to-live': 1,
        'nested-owned': 1,
        'auto-churn': 1,
        'always-continue': 1,
        'exception-defer': 2,
    }[case]
    if stats['last_collected'] < minimum:
        raise RuntimeError(
            f'{case}: last_collected {stats["last_collected"]} < {minimum}')
    if case in ('auto-churn', 'always-continue'):
        if stats['polls'] <= 0 or stats['collections'] <= 0:
            raise RuntimeError(f'{case}: no automatic poll/collection: {stats!r}')
        if stats['total_collected'] <= 50:
            raise RuntimeError(
                f'{case}: total_collected {stats["total_collected"]} <= 50')
        if stats['weak_dead'] <= 0:
            raise RuntimeError(f'{case}: no retired Weak handle: {stats!r}')
    return stats


def case_project(out: Path, role: str, case: str) -> tuple[Path, Path, str, str]:
    project = out / 'projects' / role / case
    (project / 'src').mkdir(parents=True, exist_ok=True)
    source = (HERE / 'source.wz').read_text(encoding='utf-8')
    source_path = project / 'src/main.wz'
    source_path.write_text(source, encoding='utf-8')
    manifest = project / 'lang.toml'
    manifest.write_text(MANIFEST_TEXT, encoding='utf-8')
    return project, manifest, digest(source_path), digest(manifest)


def build_cli(role: str, case: str, cli: Path, project: Path, manifest: Path,
              case_dir: Path, args, out: Path, log: list[dict],
              env: dict[str, str], meta: dict) -> tuple[dict, dict]:
    directory = case_dir / 'cli'
    directory.mkdir(parents=True, exist_ok=True)
    record = run_command(
        [cli, 'build', '--project', manifest, '--backend', 'python',
         '--out-dir', directory, '--format', 'json'],
        project, args.timeout, out, log, f'{role}-{case}-cli', env,
        args.strace, audit_allowed={str(cli.resolve())},
        trace_scope=COMPILER_TRACE_SCOPE, meta=meta)
    require_ok(record)
    document = parse_json_record(record)
    if document.get('status') != 'ok' or document.get('diagnostics'):
        raise RuntimeError(f'{record["label"]}: CLI build failed: {document}')
    return record, entry_hashes(directory, record['label'])


def build_api(role: str, case: str, api_kind: str, api_tool: Path,
              project: Path, manifest: Path, case_dir: Path, args,
              out: Path, log: list[dict], env: dict[str, str],
              meta: dict) -> tuple[dict, dict]:
    directory = case_dir / 'api'
    directory.mkdir(parents=True, exist_ok=True)
    if api_kind == 'helper':
        argv = [api_tool, '--project', manifest, '--out-dir', directory]
    else:
        argv = [api_tool, '--project', manifest, '--out-dir', directory,
                '--format', 'json']
    record = run_command(
        argv, project, args.timeout, out, log, f'{role}-{case}-{api_kind}',
        env, args.strace, audit_allowed={str(api_tool.resolve())},
        trace_scope=COMPILER_TRACE_SCOPE, meta=meta)
    require_ok(record)
    document = parse_json_record(record)
    if document.get('status') != 'ok':
        raise RuntimeError(f'{record["label"]}: API emission failed: {document}')
    return record, entry_hashes(directory, record['label'])


def run_case(role: str, case: str, api_kind: str, cli: Path, api_tool: Path,
             args, out: Path, log: list[dict], env: dict[str, str],
             observer: Path) -> dict:
    case_dir = out / role / case
    case_dir.mkdir(parents=True, exist_ok=True)
    result = {
        'role': role,
        'case': case,
        'status': 'failed',
        'api_kind': api_kind,
        'steps': {},
        'errors': [],
        'source_sha256': None,
        'manifest_sha256': None,
    }
    errors = result['errors']

    def save() -> dict:
        write_json(case_dir / 'result.json', result)
        return result

    try:
        project, manifest, source_sha, manifest_sha = case_project(
            out, role, case)
        result['project'] = str(project)
        result['manifest'] = str(manifest)
        result['source_sha256'] = source_sha
        result['manifest_sha256'] = manifest_sha
        if source_sha != SOURCE_SHA256:
            raise RuntimeError(f'{case}: project source changed: {source_sha}')
    except Exception as error:
        errors.append(f'project: {error}')
        return save()

    common = {'category': 'main', 'role': role, 'case': case,
              'source_sha256': source_sha}

    try:
        record, cli_entries = build_cli(
            role, case, cli, project, manifest, case_dir, args, out, log,
            env, dict(common, step='cli'))
        result['steps']['cli'] = {
            'status': 'ok', 'label': record['label'], 'exit': record['exit'],
            'elapsed_seconds': record['elapsed_seconds'],
            'entries': cli_entries,
        }
    except Exception as error:
        result['steps']['cli'] = {'status': 'failed', 'error': str(error)}
        errors.append(f'cli: {error}')
        return save()

    try:
        record, api_entries = build_api(
            role, case, api_kind, api_tool, project, manifest, case_dir, args,
            out, log, env, dict(common, step=api_kind))
        result['steps'][api_kind] = {
            'status': 'ok', 'label': record['label'], 'exit': record['exit'],
            'elapsed_seconds': record['elapsed_seconds'],
            'entries': api_entries,
        }
    except Exception as error:
        result['steps'][api_kind] = {'status': 'failed', 'error': str(error)}
        errors.append(f'{api_kind}: {error}')
        return save()

    cli_dir = case_dir / 'cli'
    api_dir = case_dir / 'api'
    try:
        compared = compare_generated_files(
            cli_dir, api_dir, f'{role}/{case}')
        if compared != cli_entries:
            raise RuntimeError(
                f'{role}/{case}: compared hashes differ from CLI entries')
        result['steps']['bytes'] = {'status': 'ok', **compared}
    except Exception as error:
        result['steps']['bytes'] = {'status': 'failed', 'error': str(error)}
        errors.append(f'bytes: {error}')
        return save()

    try:
        if api_kind == 'helper':
            rows, metadata_document, metadata_path = read_reference_metadata(
                api_dir, f'{role}/{case}')
            api_metadata = {
                'kind': 'helper-metadata.json',
                'path': str(metadata_path),
                'sha256': digest(metadata_path),
                'functions': rows,
            }
            write_json(case_dir / 'api-metadata.json', metadata_document)
        else:
            rows, metadata_document = read_candidate_metadata(
                record, f'{role}/{case}')
            api_metadata = {
                'kind': 'pythonobs-stdout-symbols',
                'path': record['stdout_path'],
                'sha256': record['stdout_sha256'],
                'canonical_sha256': canonical_sha(metadata_document),
                'functions': rows,
            }
            write_json(case_dir / 'api-metadata.json', metadata_document)
        result['api_metadata'] = api_metadata
        result['source_metadata'] = source_metadata(api_kind, compared)
    except Exception as error:
        result['steps']['metadata'] = {'status': 'failed',
                                       'error': str(error)}
        errors.append(f'metadata: {error}')
        return save()

    try:
        crosscheck = cli_metadata_crosscheck(
            cli_dir, rows, f'{role}/{case}')
        result['steps']['cli_metadata'] = {'status': 'ok', **crosscheck}
    except Exception as error:
        result['steps']['cli_metadata'] = {'status': 'failed',
                                            'error': str(error)}
        errors.append(f'cli_metadata: {error}')
        return save()

    try:
        projection = project_metadata(
            cli_dir, case_dir, rows,
            'reference helper metadata' if api_kind == 'helper'
            else 'candidate pythonobs symbols')
        result['metadata_projection'] = projection
        result['steps']['metadata'] = {'status': 'ok',
                                       'sha256': projection['projected_sha256']}
    except Exception as error:
        result['steps']['metadata'] = {'status': 'failed',
                                       'error': str(error)}
        errors.append(f'metadata projection: {error}')
        return save()

    try:
        record = run_command(
            [args.python, '-s', observer, cli_dir, case],
            case_dir, args.timeout, out, log, f'{role}-{case}-observer',
            env, args.strace,
            audit_allowed={str(args.python.resolve())},
            trace_scope=OBSERVER_TRACE_SCOPE,
            meta=dict(common, step='observer'))
        require_ok(record)
        lines = [line for line in record['stdout'].splitlines() if line.strip()]
        if not lines:
            raise RuntimeError(f'{record["label"]}: observer printed no JSON')
        try:
            observed = json.loads(lines[-1],
                                  parse_constant=_reject_json_constant)
        except (json.JSONDecodeError, CorpusError) as error:
            raise RuntimeError(
                f'{record["label"]}: observer JSON is not strict: {error}') from error
        stats = check_observation(case, observed)
        write_json(case_dir / 'observation.json', observed)
        result['steps']['observer'] = {
            'status': 'ok', 'label': record['label'], 'exit': record['exit'],
            'elapsed_seconds': record['elapsed_seconds'],
            'document': observed,
            'stats': stats,
        }
    except Exception as error:
        result['steps']['observer'] = {'status': 'failed',
                                       'error': str(error)}
        errors.append(f'observer: {error}')
        return save()

    try:
        final_entries = entry_hashes(cli_dir, f'{role}/{case}-final')
        if final_entries != cli_entries:
            raise RuntimeError(
                f'{role}/{case}: CLI generated files changed after observation')
        final_metadata = digest(cli_dir / 'metadata.json')
        if final_metadata != result['metadata_projection']['projected_sha256']:
            raise RuntimeError(
                f'{role}/{case}: metadata.json changed after observation')
        result['generated_initial'] = cli_entries
        result['generated_final'] = final_entries
        result['metadata_initial_sha256'] = result['metadata_projection'][
            'projected_sha256']
        result['metadata_final_sha256'] = final_metadata
        result['steps']['final_bytes'] = {'status': 'ok', **final_entries}
    except Exception as error:
        result['steps']['final_bytes'] = {'status': 'failed',
                                          'error': str(error)}
        errors.append(f'final_bytes: {error}')
        return save()

    result['status'] = 'passed' if not errors else 'failed'
    return save()


def default_stdlib_root(binary: Path, label: str) -> Path | None:
    data = binary.read_bytes()
    suffix = b'/stdlib\x00'
    found: set[str] = set()
    offset = 0
    while True:
        index = data.find(suffix, offset)
        if index < 0:
            break
        end = index + len(suffix) - 1
        begin = data.rfind(b'\x00', 0, index) + 1
        raw = data[begin:end]
        if raw.startswith(b'/'):
            try:
                found.add(raw.decode('utf-8'))
            except UnicodeDecodeError:
                pass
        offset = index + len(suffix)
    if len(found) > 1:
        raise RuntimeError(
            f'{label}: multiple embedded stdlib roots: {sorted(found)}')
    if not found:
        return None
    root = Path(found.pop())
    if not root.is_absolute() or not root.is_dir():
        raise RuntimeError(
            f'{label}: embedded stdlib root is not an absolute directory: {root}')
    if not any(path.is_file() for path in root.rglob('*.wz')):
        raise RuntimeError(
            f'{label}: embedded stdlib root has no Wz sources: {root}')
    return root


def reference_stdlib_roots(args) -> dict[str, dict]:
    found: dict[str, dict] = {}
    for label, binary in (('reference_cli', args.cli),
                          ('reference_helper', args.helper)):
        if binary is None or not binary.is_file():
            continue
        root = default_stdlib_root(binary, label)
        if root is None:
            found[label] = {'root': None, 'wz_files': 0}
            continue
        sources = sorted(path for path in root.rglob('*.wz') if path.is_file())
        found[label] = {
            'root': str(root),
            'wz_files': len(sources),
            'equals_owner_stdlib_tree': (
                root.resolve() == (args.root / 'stdlib').resolve()),
        }
    return found


def historical_driver_details(args) -> dict:
    path = Path(str(args.api_driver.parents[3])) / 'driver-inputs.json'
    if not path.is_file():
        raise RuntimeError(
            f'candidate API driver has no historical driver-inputs.json: {path}')
    document = load_strict_json(path, 'driver-inputs')
    recorded = document.get('candidate', {}).get('api_driver', {})
    actual = digest(args.api_driver)
    if recorded.get('sha256') != actual:
        raise RuntimeError(
            f'API driver SHA {actual} does not match historical record '
            f'{recorded.get("sha256")}')
    source = document.get('source', {})
    old_root = Path(source.get('path', ''))
    if not old_root.is_dir():
        raise RuntimeError(f'historical driver Source is absent: {old_root}')
    checked = 0
    for relative, expected in source.get('wzcc_modules', {}).items():
        current = old_root / relative
        if not current.is_file() or digest(current) != expected:
            raise RuntimeError(
                f'historical driver Source changed: {current}')
        checked += 1
    for relative, expected in source.get('top_level_files', {}).items():
        current = old_root / relative
        if not current.is_file() or digest(current) != expected:
            raise RuntimeError(
                f'historical driver top-level Source changed: {current}')
        checked += 1
    driver_root = old_root.parent / 'tests/pythonobs'
    for relative, expected_key in (
            ('src/main.wz', 'driver_entry_source'),
            ('lang.toml', 'driver_manifest'),
            ('README.md', 'driver_readme')):
        current = driver_root / relative
        expected = source.get(expected_key)
        if not current.is_file() or digest(current) != expected:
            raise RuntimeError(
                f'historical driver support file changed: {current}')
    build = recorded.get('build_command', {})
    return {
        'label': 'historical driver build record; not recompiled by this run',
        'driver_inputs_path': str(path),
        'driver_inputs_sha256': digest(path),
        'recorded_driver_sha256': recorded.get('sha256'),
        'actual_driver_sha256': actual,
        'driver_initial_sha256': actual,
        'driver_final_sha256': actual,
        'old_source_root': str(old_root),
        'old_source_tree_sha256': source.get('tree_sha256'),
        'old_source_wz_files': source.get('wz_count'),
        'compiled_wzcc_modules': source.get('compiled_wzcc_modules'),
        'compiled_driver_entry': source.get('compiled_driver_entry'),
        'driver_entry_source_sha256': source.get('driver_entry_source'),
        'checked_source_files': checked,
        'historical_build': {
            'label': build.get('label'),
            'tool_argv': build.get('tool_argv'),
            'exit': build.get('exit'),
            'timed_out': build.get('timed_out'),
            'cleanup_complete': build.get('cleanup_complete'),
            'abandoned_pipes': build.get('abandoned_pipes'),
            'elapsed_seconds': build.get('elapsed_seconds'),
            'stdout_sha256': build.get('stdout_sha256'),
            'stderr_sha256': build.get('stderr_sha256'),
            'trace_sha256': build.get('trace_sha256'),
        },
        'source_identity_caveat': (
            'The 55d5 pythonobs was compiled from old Source tree 727b, not '
            'from current Source da69.  It supplies real published symbols '
            'only after exact CLI/API program.py and langrt.py equality.  '
            'This run does not claim current da69 PythonEmitter API parity.'),
        'current_source_same_api_proof': False,
    }


def historical_source_paths(details: dict) -> list[Path]:
    root = Path(details['old_source_root'])
    return sorted(path for path in root.rglob('*.wz') if path.is_file()) + [
        root.parent / 'tests/pythonobs/src/main.wz',
        root.parent / 'tests/pythonobs/lang.toml',
        root.parent / 'tests/pythonobs/README.md',
    ]


def prepare_candidate_driver(args, out: Path) -> dict:
    root = out / 'candidate' / 'driver' / 'root'
    root.mkdir(parents=True, exist_ok=True)
    target = root / 'pythonobs'
    source_sha = digest(args.api_driver)
    shutil.copy2(args.api_driver, target)
    target.chmod(0o755)
    resources = args.candidate_resources
    for name in ('stdlib', 'runtime'):
        link = root / name
        if link.exists() or link.is_symlink():
            link.unlink()
        try:
            link.symlink_to(resources / name, target_is_directory=True)
        except OSError:
            shutil.copytree(resources / name, link)
    target_sha = digest(target)
    if target_sha != source_sha:
        raise RuntimeError(
            f'copied API driver changed: {source_sha} != {target_sha}')
    return {
        'source_path': str(args.api_driver),
        'source_sha256': source_sha,
        'path': str(target),
        'initial_sha256': target_sha,
        'final_sha256': digest(target),
        'resources': str(resources),
    }


def snapshot_inputs(args, resources: Path | None, historical: dict | None,
                    out: Path) -> dict[str, str]:
    paths: set[Path] = set()
    out_resolved = out.resolve()

    def add(path: Path | None) -> None:
        if path is None:
            return
        path = Path(path)
        if not path.exists():
            return
        if path.is_dir():
            candidates = [p for p in path.rglob('*') if p.is_file()]
        elif path.is_file():
            candidates = [path]
        else:
            return
        for current in candidates:
            try:
                current.resolve().relative_to(out_resolved)
                continue
            except ValueError:
                pass
            paths.add(current.resolve())

    add(HERE / 'source.wz')
    add(HERE / 'observe_language_gc.py')
    add(Path(__file__).resolve())
    add(HERE / 'README.md')
    add(HERE / 'runner_controls.py')
    add(COMPILER_ROOT / 'tests/python/CMakeLists.txt')
    add(SELFHOST / 'corpus.py')
    add(SELFHOST / 'corpus.json')
    add(args.root / 'stdlib')
    for pattern in ('runtime/python/*.py',):
        for path in (args.root).glob(pattern):
            add(path)
    for tool in (args.cli, args.helper, args.candidate_cli, args.api_driver,
                 args.python, args.strace):
        add(tool)
    if resources is not None:
        add(resources / 'stdlib')
        add(resources / 'runtime' / 'python')
    for label, binary in (('reference_cli', args.cli),
                          ('reference_helper', args.helper)):
        if binary is not None and binary.is_file():
            root = default_stdlib_root(binary, label)
            if root is not None:
                add(root)
    if historical is not None:
        add(Path(historical['driver_inputs_path']))
        for path in historical_source_paths(historical):
            add(path)
    if args.toolchain_root is not None:
        for relative in (
                'llvm-22.1.8/bin/opt',
                'llvm-22.1.8/bin/llc',
                'llvm-22.1.8/bin/clang',
                'llvm-22.1.8/bin/clang++',
                'llvm-22.1.8/bin/ld.lld',
                'libxml2-legacy-2.13.9/usr/lib/libxml2.so.2.13.9'):
            add(args.toolchain_root / relative)
    return {str(path): digest(path) for path in sorted(paths)}


def input_summary(snapshot: dict[str, str], args, resources: Path | None,
                  historical: dict | None) -> dict:
    def count(predicate) -> int:
        return sum(1 for key in snapshot if predicate(key))

    return {
        'total_entries': len(snapshot),
        'source_entries': count(lambda key: key.endswith('/language_gc/source.wz')),
        'observer_entries': count(
            lambda key: key.endswith('/language_gc/observe_language_gc.py')),
        'runner_entries': count(
            lambda key: key.endswith('/language_gc/run_language_gc.py')),
        'stdlib_wz_entries': count(
            lambda key: '/stdlib/' in key and key.endswith('.wz')),
        'stdlib_wz_distinct_hashes': len({
            value for key, value in snapshot.items()
            if '/stdlib/' in key and key.endswith('.wz')}),
        'runtime_py_entries': count(
            lambda key: key.endswith(('/runtime/python/langrt.py',
                                      '/runtime/python/unicode18.py'))),
        'runtime_py_distinct_hashes': len({
            value for key, value in snapshot.items()
            if key.endswith(('/runtime/python/langrt.py',
                             '/runtime/python/unicode18.py'))}),
        'historical_source_entries': count(
            lambda key: ('/ef8df82c798c25c622235f2e/' in key)),
        'reference_cli': str(args.cli) if args.cli else None,
        'reference_helper': str(args.helper) if args.helper else None,
        'candidate_cli': str(args.candidate_cli) if args.candidate_cli else None,
        'api_driver': str(args.api_driver) if args.api_driver else None,
        'candidate_resources': str(resources) if resources else None,
        'reference_stdlib': reference_stdlib_roots(args),
        'historical_driver_inputs': (
            historical['driver_inputs_path'] if historical else None),
        'note': 'counts summarize the hash inventory; they are not a tree claim',
    }


PAIRED_ROLE_COUNT = 2
EMIT_DIRECTORY_COUNT_PER_ROLE = 2
GENERATED_FILE_NAMES = ('program.py', 'langrt.py')


def expected_main_commands(case_count: int) -> int:
    return case_count * 3 * 2


def expected_generated_files(case_count: int) -> int:
    return (case_count * PAIRED_ROLE_COUNT * EMIT_DIRECTORY_COUNT_PER_ROLE
            * len(GENERATED_FILE_NAMES))


def count_commands(log: list[dict]) -> dict:
    main = [record for record in log if record.get('category') == 'main']
    extras = [record for record in log if record.get('category') == 'extra']
    by_role: dict[str, int] = {}
    by_step: dict[str, int] = {}
    for record in main:
        by_role[record.get('role', '?')] = by_role.get(
            record.get('role', '?'), 0) + 1
        by_step[record.get('step', '?')] = by_step.get(
            record.get('step', '?'), 0) + 1
    return {
        'main_commands': len(main),
        'extra_commands': len(extras),
        'by_role': by_role,
        'by_step': by_step,
    }


